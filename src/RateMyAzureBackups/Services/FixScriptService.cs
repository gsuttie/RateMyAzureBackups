using System.Text;
using RateMyAzureBackups.Models;

namespace RateMyAzureBackups.Services;

/// <summary>Generates PowerShell (Az module) remediation scripts for a job activity, for either vault product.</summary>
public static class FixScriptService
{
    public sealed record FixOption(string Key, string Label, bool Enabled);

    /// <summary>Explanation and default options for an activity's classification.</summary>
    public static (string Explanation, List<FixOption> Options) Describe(BackupJobActivity a, BackupFlowKind flow)
    {
        var product = flow.Label();
        var deletedSource = a.ErrorCode.Contains("NotFound", StringComparison.OrdinalIgnoreCase) || a.ErrorCode.Contains("NotPresent", StringComparison.OrdinalIgnoreCase);

        if (a.Classification == "Persistent failure")
            return ($"Triggers an on-demand backup of '{a.ItemName}' on {product} '{TargetName(a)}' once the cause ({(string.IsNullOrEmpty(a.ErrorCode) ? "see the job details" : a.ErrorCode)}) has been fixed, " +
                    "and lists the latest jobs so you can confirm the item has a current recovery point again. " +
                    (deletedSource ? "Because the source resource appears to be gone, the script can also stop protection so the item stops failing." : ""),
                [
                    new("adhocBackup", "Run an on-demand backup", !deletedSource),
                    new("listJobs", "List the item's recent jobs", true),
                    new("stopProtection", "Stop protection (retain data) — only if the source is gone", deletedSource),
                ]);

        if (a.Classification == "Transient failure")
            return ($"Verifies that '{a.ItemName}' recovered from its transient failure by listing recovery points and recent jobs, " +
                    "and optionally takes an extra on-demand backup for a fresh recovery point.",
                [
                    new("listRecoveryPoints", "List recent recovery points", true),
                    new("listJobs", "List the item's recent jobs", true),
                    new("adhocBackup", "Run an on-demand backup", false),
                ]);

        return ($"Collects what you need to review '{a.ItemName}': the item's protection state, its recent jobs and recovery points, " +
                "so you can decide whether the warning or single failure needs a fix.",
            [
                new("showItem", "Show the item's protection state", true),
                new("listJobs", "List the item's recent jobs", true),
                new("listRecoveryPoints", "List recent recovery points", false),
            ]);
    }

    public static string Generate(BackupJobActivity a, BackupFlowKind flow, IEnumerable<FixOption> options)
    {
        var enabled = options.Where(o => o.Enabled).Select(o => o.Key).ToHashSet();
        return flow == BackupFlowKind.RecoveryServices ? GenerateRecoveryServices(a, enabled) : GenerateBackupVault(a, enabled);
    }

    private static string TargetName(BackupJobActivity a)
    {
        var vaultId = BackupDiscoveryService.VaultIdOf(a.ItemId);
        return vaultId == a.ItemId ? "<vault>" : Services.Azure.Json.LastSegment(vaultId);
    }

    private static string Header(BackupJobActivity a, string module, string vaultName)
    {
        var sb = new StringBuilder();
        sb.AppendLine("# Backup fix script — generated by RateMyAzureBackups");
        sb.AppendLine($"# Item: {a.ItemName} ({a.WorkloadType})");
        sb.AppendLine($"# Vault: {vaultName}");
        sb.AppendLine($"# Classification: {a.Classification}");
        if (!string.IsNullOrEmpty(a.ErrorCode)) sb.AppendLine($"# Last error: {a.ErrorCode}");
        sb.AppendLine();
        sb.AppendLine("# ─── Prerequisites ───");
        sb.AppendLine($"# Requires the {module} PowerShell module. Run Connect-AzAccount first.");
        sb.AppendLine("# Review every line before running: on-demand backups and stop-protection CHANGE the vault.");
        sb.AppendLine();
        sb.AppendLine($"$vaultName = \"{vaultName}\"");
        sb.AppendLine("$resourceGroup = \"<VAULT-RESOURCE-GROUP>\"  # <- update this");
        sb.AppendLine($"$itemName = \"{a.ItemName}\"");
        sb.AppendLine();
        return sb.ToString();
    }

    private static string GenerateRecoveryServices(BackupJobActivity a, HashSet<string> enabled)
    {
        var vaultName = TargetName(a);
        var sb = new StringBuilder(Header(a, "Az.RecoveryServices", vaultName));
        var (bmt, wlt) = RsvTypes(a.WorkloadType);

        sb.AppendLine("$vault = Get-AzRecoveryServicesVault -Name $vaultName -ResourceGroupName $resourceGroup");
        sb.AppendLine($"$item = Get-AzRecoveryServicesBackupItem -VaultId $vault.ID -BackupManagementType {bmt} -WorkloadType {wlt} -FriendlyName $itemName");
        sb.AppendLine();

        if (enabled.Contains("showItem"))
        {
            sb.AppendLine("# ─── Protection state ───");
            sb.AppendLine("$item | Select-Object Name, ProtectionState, ProtectionStatus, LastBackupStatus, LastBackupTime, ProtectionPolicyName, HealthStatus | Format-List");
            sb.AppendLine();
        }

        if (enabled.Contains("listJobs"))
        {
            sb.AppendLine("# ─── Recent jobs for this item ───");
            sb.AppendLine("Get-AzRecoveryServicesBackupJob -VaultId $vault.ID -From (Get-Date).AddDays(-7).ToUniversalTime() |");
            sb.AppendLine("    Where-Object { $_.WorkloadName -eq $itemName } |");
            sb.AppendLine("    Select-Object JobId, Operation, Status, StartTime, EndTime, ErrorDetails | Format-Table -AutoSize");
            sb.AppendLine();
        }

        if (enabled.Contains("listRecoveryPoints"))
        {
            sb.AppendLine("# ─── Recovery points from the last 14 days ───");
            sb.AppendLine("Get-AzRecoveryServicesBackupRecoveryPoint -Item $item -VaultId $vault.ID -StartDate (Get-Date).AddDays(-14).ToUniversalTime() -EndDate (Get-Date).ToUniversalTime() |");
            sb.AppendLine("    Select-Object RecoveryPointTime, RecoveryPointType, RecoveryPointTier | Format-Table -AutoSize");
            sb.AppendLine();
        }

        if (enabled.Contains("adhocBackup"))
        {
            sb.AppendLine("# ─── On-demand backup (keep the recovery point 30 days) ───");
            sb.AppendLine("$job = Backup-AzRecoveryServicesBackupItem -Item $item -VaultId $vault.ID -ExpiryDateTimeUTC (Get-Date).AddDays(30).ToUniversalTime()");
            sb.AppendLine("Wait-AzRecoveryServicesBackupJob -Job $job -VaultId $vault.ID -Timeout 7200");
            sb.AppendLine("Get-AzRecoveryServicesBackupJobDetail -Job $job -VaultId $vault.ID | Select-Object Status, ErrorDetails");
            sb.AppendLine();
        }

        if (enabled.Contains("stopProtection"))
        {
            sb.AppendLine("# ─── Stop protection but RETAIN the existing recovery points (source resource is gone) ───");
            sb.AppendLine("Disable-AzRecoveryServicesBackupProtection -Item $item -VaultId $vault.ID -Confirm:$true");
            sb.AppendLine();
        }

        if (enabled.Count == 0)
            sb.AppendLine("# No options selected — toggle the options above to generate a script.");

        sb.AppendLine("Write-Host \"Done — review the output for '$itemName' in vault '$vaultName'.\" -ForegroundColor Green");
        return sb.ToString();
    }

    private static string GenerateBackupVault(BackupJobActivity a, HashSet<string> enabled)
    {
        var vaultName = TargetName(a);
        var sb = new StringBuilder(Header(a, "Az.DataProtection", vaultName));

        sb.AppendLine("$instance = Get-AzDataProtectionBackupInstance -ResourceGroupName $resourceGroup -VaultName $vaultName |");
        sb.AppendLine("    Where-Object { $_.Property.FriendlyName -eq $itemName -or $_.Name -like \"$itemName*\" } | Select-Object -First 1");
        sb.AppendLine("if (-not $instance) { throw \"Backup instance '$itemName' not found in vault '$vaultName'.\" }");
        sb.AppendLine();

        if (enabled.Contains("showItem"))
        {
            sb.AppendLine("# ─── Protection state ───");
            sb.AppendLine("$instance.Property | Select-Object FriendlyName, CurrentProtectionState, ProtectionStatus, @{n='Policy';e={$_.PolicyInfo.PolicyId.Split('/')[-1]}} | Format-List");
            sb.AppendLine("$instance.Property.ProtectionErrorDetail | Format-List");
            sb.AppendLine();
        }

        if (enabled.Contains("listJobs"))
        {
            sb.AppendLine("# ─── Recent jobs for this instance ───");
            sb.AppendLine("Get-AzDataProtectionJob -ResourceGroupName $resourceGroup -VaultName $vaultName |");
            sb.AppendLine("    Where-Object { $_.BackupInstanceFriendlyName -eq $itemName -and $_.StartTime -gt (Get-Date).AddDays(-7) } |");
            sb.AppendLine("    Select-Object Operation, Status, StartTime, EndTime, @{n='Error';e={$_.ErrorDetail.Code}} | Format-Table -AutoSize");
            sb.AppendLine();
        }

        if (enabled.Contains("listRecoveryPoints"))
        {
            sb.AppendLine("# ─── Recovery points from the last 14 days ───");
            sb.AppendLine("Get-AzDataProtectionRecoveryPoint -ResourceGroupName $resourceGroup -VaultName $vaultName -BackupInstanceName $instance.Name |");
            sb.AppendLine("    Where-Object { $_.Property.RecoveryPointTime -gt (Get-Date).AddDays(-14) } |");
            sb.AppendLine("    Select-Object @{n='Time';e={$_.Property.RecoveryPointTime}}, @{n='Type';e={$_.Property.RecoveryPointType}} | Format-Table -AutoSize");
            sb.AppendLine();
        }

        if (enabled.Contains("adhocBackup"))
        {
            sb.AppendLine("# ─── On-demand backup using the policy's default backup rule and retention tag ───");
            sb.AppendLine("$policy = Get-AzDataProtectionBackupPolicy -ResourceGroupName $resourceGroup -VaultName $vaultName |");
            sb.AppendLine("    Where-Object { $_.Id -eq $instance.Property.PolicyInfo.PolicyId }");
            sb.AppendLine("$backupRule = ($policy.Property.PolicyRule | Where-Object { $_.ObjectType -eq 'AzureBackupRule' } | Select-Object -First 1).Name");
            sb.AppendLine("Backup-AzDataProtectionBackupInstanceAdhoc -ResourceGroupName $resourceGroup -VaultName $vaultName -BackupInstanceName $instance.Name `");
            sb.AppendLine("    -BackupRuleOptionRuleName $backupRule -TriggerOptionRetentionTagOverride Default");
            sb.AppendLine();
        }

        if (enabled.Contains("stopProtection"))
        {
            sb.AppendLine("# ─── Stop protection but RETAIN the existing recovery points (source resource is gone) ───");
            sb.AppendLine("Stop-AzDataProtectionBackupInstanceProtection -ResourceGroupName $resourceGroup -VaultName $vaultName -BackupInstanceName $instance.Name -Confirm:$true");
            sb.AppendLine();
        }

        if (enabled.Count == 0)
            sb.AppendLine("# No options selected — toggle the options above to generate a script.");

        sb.AppendLine("Write-Host \"Done — review the output for '$itemName' in vault '$vaultName'.\" -ForegroundColor Green");
        return sb.ToString();
    }

    /// <summary>Az.RecoveryServices -BackupManagementType / -WorkloadType values for a workload label.</summary>
    internal static (string BackupManagementType, string WorkloadType) RsvTypes(string workloadLabel) => workloadLabel switch
    {
        "Azure Files" => ("AzureStorage", "AzureFiles"),
        "SQL in Azure VM" => ("AzureWorkload", "MSSQL"),
        "SAP HANA in Azure VM" => ("AzureWorkload", "SAPHanaDatabase"),
        "MARS agent (files and folders)" => ("MAB", "FileFolder"),
        _ => ("AzureVM", "AzureVM")
    };
}
