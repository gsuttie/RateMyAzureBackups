// End-to-end walkthrough of RateMyAzureBackups (sample data mode) in headless Chromium.
import { chromium } from 'playwright';
import path from 'node:path';

const base = process.env.BASE_URL || 'http://localhost:5220';
import { mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const outDir = path.join(path.dirname(fileURLToPath(import.meta.url)), 'screenshots');
mkdirSync(outDir, { recursive: true });
const errors = [];
let step = 0;

const browser = await chromium.launch({ executablePath: process.env.PW_EXE || undefined });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 }, colorScheme: 'light' });
page.on('console', m => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
page.on('pageerror', e => errors.push('pageerror: ' + e.message));

async function shot(name) {
  step++;
  const file = path.join(outDir, `${String(step).padStart(2, '0')}-${name}.png`);
  await page.screenshot({ path: file, fullPage: true });
  console.log('shot', file);
}
async function expectText(text) {
  try {
    await page.getByText(text, { exact: false }).first().waitFor({ timeout: 10000 });
    console.log('  ok:', text);
  } catch (e) {
    await shot('failure');
    console.log('URL:', page.url());
    console.log('PAGE TEXT:', (await page.locator('body').innerText()).slice(0, 2000));
    throw e;
  }
}

// Home
await page.goto(base);
await expectText('How good are your Azure backups?');
await shot('home');

// Enter sample data mode -> Recovery Services scope
await page.getByRole('button', { name: /Try with sample data/ }).click();
await page.waitForURL(/recovery-services/);
await expectText('Choose what to scan');
await page.locator('li.sub-row').first().waitFor();
await page.locator('.sub-count.has').first().waitFor({ timeout: 10000 });
await shot('rsv-scope');

// Select all relevant and scan
await page.getByRole('button', { name: /Select all with Recovery Services vaults/ }).click();
const scanBtn = page.getByRole('button', { name: /^Scan 2 subscriptions/ });
await scanBtn.waitFor();
await scanBtn.click();
await page.waitForURL(/recovery-services\/grades/, { timeout: 20000 });
await expectText('Findings');
const overall = await page.locator('.overall .grade-badge.lg').textContent();
console.log('  Recovery Services overall grade:', overall);
if (overall !== 'F') throw new Error('expected overall F, got ' + overall);
const ratingCount = await page.locator('article.rating').count();
console.log('  ratings:', ratingCount);
await expectText('Virtual machines without backup');
await expectText('vm-jumpbox');
await shot('rsv-grades');

// Expand a collapsed rating and a finding fix, then a policy row
await page.locator('article.rating:not(.open) .rating-row').first().click();
await expectText('Score breakdown');
await page.locator('ul.findings li button.link').first().click();
await page.locator('.fix').first().waitFor();
await page.locator('tr.policy-row').first().click();
await page.locator('.policy-detail').first().waitFor();
await shot('rsv-grades-expanded');

// Report modal
await page.getByRole('button', { name: /Summary report/ }).first().click();
await expectText('Backup Summary Report');
await page.getByRole('button', { name: 'Extensive' }).click();
await expectText('Extensive Backup Findings');
await shot('rsv-report');
await page.locator('.modal-head .icon-btn').click();

// Jobs step
await page.getByRole('link', { name: /Analyse jobs/ }).first().click();
await page.waitForURL(/recovery-services\/jobs/);
await expectText('Analyse the backup jobs');
await page.locator('select').first().selectOption({ label: 'rsv-contoso-legacy (3 protected items)' });
await page.getByRole('button', { name: /Analyse jobs/ }).click();
await page.locator('article.activity').first().waitFor({ timeout: 15000 });
await expectText('Failure assessment');
await expectText('Persistent failure');
await expectText('Needs review');
await expectText('vm-fileserver');
await shot('rsv-jobs');

// Changes modal + fix script modal
await page.getByRole('button', { name: /Changes vs previous period/ }).click();
await expectText('Changes vs the previous');
await page.locator('.modal-head .icon-btn').click();
await page.locator('article.activity button.btn').first().click();
await expectText('generated by RateMyAzureBackups');
await expectText('Az.RecoveryServices');
await shot('rsv-fix-script');
await page.locator('.modal-head .icon-btn').click();

// Step bar navigation back to grades keeps state
await page.locator('.stepbar a[href="/recovery-services/grades"]').click();
await page.waitForURL(/recovery-services\/grades/);
await expectText('Findings');

// Backup vault flow via the top tab
await page.getByRole('link', { name: /^Backup vaults$/ }).click();
await page.waitForURL(/backup-vaults/);
await expectText('Choose what to scan');
await page.locator('.sub-count.has').first().waitFor({ timeout: 10000 });
await page.getByRole('button', { name: /Select all with Backup vaults/ }).click();
await page.getByRole('button', { name: /^Scan 2 subscriptions/ }).click();
await page.waitForURL(/backup-vaults\/grades/, { timeout: 20000 });
const bvOverall = await page.locator('.overall .grade-badge.lg').textContent();
console.log('  Backup vault overall grade:', bvOverall);
if (bvOverall !== 'E') throw new Error('expected overall E, got ' + bvOverall);
await expectText('ProtectionError');
await expectText('aks-contoso-shared');
await shot('bv-grades');

await page.getByRole('link', { name: /Analyse jobs/ }).first().click();
await page.waitForURL(/backup-vaults\/jobs/);
await page.locator('select').first().selectOption({ label: 'bv-contoso-shared (2 backup instances)' });
await page.getByRole('button', { name: /Analyse jobs/ }).click();
await page.locator('article.activity').first().waitFor({ timeout: 15000 });
await page.locator('article.activity button.btn').first().click();
await expectText('Az.DataProtection');
await shot('bv-fix-script');
await page.locator('.modal-head .icon-btn').click();

// The Recovery Services flow's state survived while we used the other flow
await page.getByRole('link', { name: /Recovery Services vaults/ }).click();
await page.waitForURL(/recovery-services$/);
await expectText('Back to grades');

// Dark theme toggle
await page.locator('.topbar .icon-btn').click();
const theme = await page.evaluate(() => document.documentElement.getAttribute('data-theme'));
console.log('  theme after toggle:', theme);
// A hard reload drops the circuit (and the in-memory scan): the wizard must fall back to Scope,
// with the subscription selection restored from sessionStorage, so one click rescans.
await page.goto(base + '/recovery-services/grades');
await expectText('Choose what to scan');
const restored = page.getByRole('button', { name: /^Scan 2 subscriptions/ });
await restored.waitFor({ timeout: 10000 });
console.log('  selection restored after reload');
await restored.click();
await page.waitForURL(/recovery-services\/grades/, { timeout: 20000 });
await expectText('Findings');
await shot('rsv-grades-dark');

// Mobile viewport
await page.setViewportSize({ width: 420, height: 900 });
await page.getByRole('link', { name: /^Backup vaults$/ }).click();
await page.waitForURL(/backup-vaults/);
await page.getByRole('button', { name: /^Scan 2 subscriptions/ }).click();
await page.waitForURL(/backup-vaults\/grades/, { timeout: 20000 });
try {
  await expectText('Backup policies');
} catch (e) {
  await shot('failure');
  console.log('PAGE TEXT:', (await page.locator('main').innerText()).slice(0, 1500));
  throw e;
}
await shot('bv-grades-mobile');

await browser.close();
if (errors.length) {
  console.log('BROWSER ERRORS:\n' + errors.join('\n'));
  process.exit(1);
}
console.log('E2E OK');
